/**
 * Stand-in for expo-haptics.
 *
 * Настоящий модуль тянет `expo-modules-core`, который на первой же строке
 * читает `globalThis.expo.EventEmitter` — в jsdom этого глобала нет, и падает
 * ИМПОРТ. С 2026-09-01 обёртка `src/lib/haptics.ts` подтягивает модуль лениво
 * и гасит отказ загрузки, так что без заглушки экран уже не рухнет — но тест,
 * который выдаёт себя за телефон (подменяет `Platform.OS`), молча остался бы
 * без вибрации по причине, к проверяемому коду отношения не имеющей. Заглушка
 * даёт такому тесту загружаемый модуль.
 *
 * Заглушка НЕ считает вызовы. Вибрация проверяется на своих уровнях:
 * `src/lib/__tests__/haptics.test.ts` подменяет этот модуль своим шпионом и
 * смотрит, ЧТО зовётся на каждой платформе (и что бывает, когда модуля в
 * сборке нет), `WheelPickerHaptics.test.tsx` подменяет обёртку `lib/haptics` и
 * смотрит, КОГДА колесо её зовёт, а
 * `explore/__tests__/PartySheetWithoutNativeHaptics.test.tsx` поднимает шторку
 * с колёсами на «старом бинаре», где модуля нет вовсе. Считать ещё и здесь
 * значило бы завести четвёртое место, где живёт то же знание.
 *
 * Что заглушка не проверяет и проверить не может: дёрнулся ли телефон. Это
 * только рукой на устройстве.
 */

