/**
 * Kazakh has no separate plural noun form after a numeral — the noun stays in
 * its base (singular) shape, so "1 қонақ" and "5 қонақ" both use "қонақ".
 * Pluralisation still lives in the dictionary, not the markup; these helpers
 * just return the invariant Kazakh word.
 */
function guestsWord(_count: number): string {
  return "қонақ";
}

/** Kazakh word for "booking" — invariant after a numeral. */
function bookingsWord(_count: number): string {
  return "бронь";
}

/** Kazakh word for "day" — invariant after a numeral. */
function daysWord(_count: number): string {
  return "күн";
}

