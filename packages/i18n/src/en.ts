/**
 * English plural of "guest": 1 guest / 2 guests. Lives here, not in the
 * component — pluralisation is part of the dictionary, not the markup.
 */
function guestsWord(count: number): string {
  return count === 1 ? "guest" : "guests";
}

/** English plural of "booking": 1 booking / 2 bookings. */
function bookingsWord(count: number): string {
  return count === 1 ? "booking" : "bookings";
}

/** English plural of "day": 1 day / 2 days. */
function daysWord(count: number): string {
  return count === 1 ? "day" : "days";
}

