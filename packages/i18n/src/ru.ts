/**
 * Русская форма слова «гость» для числа. Живёт здесь, а не в компоненте:
 * склонение — часть словаря, а не разметки.
 */
function guestsWord(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return "гостей";
  if (mod10 === 1) return "гость";
  if (mod10 >= 2 && mod10 <= 4) return "гостя";
  return "гостей";
}

/** Русская форма слова «бронь» для числа. Как и `guestsWord`, склонение —
 * часть словаря, а не разметки. */
function bookingsWord(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return "броней";
  if (mod10 === 1) return "бронь";
  if (mod10 >= 2 && mod10 <= 4) return "брони";
  return "броней";
}

/** Русская форма слова «день» для числа: 1 день, 2 дня, 5 дней. */
function daysWord(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return "дней";
  if (mod10 === 1) return "день";
  if (mod10 >= 2 && mod10 <= 4) return "дня";
  return "дней";
}

/** Общая русская тройка форм: 1 дата, 2 даты, 5 дат. В отличие от трёх функций
 * выше слово передаётся аргументом — серий событий это касается сразу в
 * нескольких формулировках, и заводить по функции на каждое слово незачем. */
function pluralRu(count: number, one: string, few: string, many: string): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

