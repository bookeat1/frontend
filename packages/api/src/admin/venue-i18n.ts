/**
 * Переименование заведения: почему одного поля `name` мало.
 *
 * Каталожные ответы отдают не колонку, а перевод:
 * `Name: r.NameI18n.Resolve(lang, r.Name)` (transport/rest/restaurants,
 * baseFromDomain), а `lang` берётся из `?lang=` или из Accept-Language —
 * который браузер подставляет сам, и для панели это всегда `ru`. Значит у
 * заведения с заполненным `name_i18n.ru` панель показывает перевод, а PATCH с
 * одним `name` пишет колонку, которую после этого никто не читает: название на
 * экране не меняется, следующее сохранение отправляет обратно старый перевод —
 * и переименовать заведение из панели невозможно вообще.
 *
 * Карту сервер ЗАМЕЩАЕТ целиком (`applyRestaurant`: `m.NameI18n = in.NameI18n`),
 * поэтому её нельзя собрать заново — только слить с той, что пришла с сервера.
 */

/** Язык панели. Панель русскоязычная, других полей ввода у названия нет. */
export const PANEL_LOCALE = "ru";

/**
 * Карта переводов названия для PATCH, или `undefined`, когда её слать не надо.
 *
 * Не надо — когда русского перевода у заведения нет: тогда читается колонка
 * `name`, и одного плоского поля достаточно. Заводить перевод там, где его не
 * было, панель не должна: это молча создаст вторую копию названия, которую
 * потом придётся поддерживать руками.
 */
export function mergeVenueNameI18n(
  current: Record<string, string> | undefined,
  name: string,
): Record<string, string> | undefined {
  if (!current || current[PANEL_LOCALE] === undefined) return undefined;
  if (current[PANEL_LOCALE] === name) return undefined; // менять нечего
  return { ...current, [PANEL_LOCALE]: name };
}
