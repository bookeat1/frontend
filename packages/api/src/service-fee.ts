/**
 * Сервисный сбор заведения (Trello GvptXfr1, решение владельца 03.09.2026):
 * показать процент гостю рядом с часами работы на карточке заведения и в
 * брони, там, где называется сумма. `Restaurant.serviceFeeBps` — ЕДИНСТВЕННЫЙ
 * источник; здесь только чистое форматирование числа, общее для сайта и
 * приложения (тот же принцип, что у `schedule.ts` — считать один раз, а не
 * двумя параллельными копиями).
 */

/**
 * Виден ли гостю блок сервисного сбора вообще — ПРАВИЛО ОДНО И ТО ЖЕ на обеих
 * поверхностях (карточка заведения, сводка брони): `null`, отсутствие поля
 * И явный `0` значат одно и то же — «сбор не показываем НИГДЕ». Компонент не
 * имеет права переизобретать это условие инлайново, отсюда отдельная функция.
 */
export function hasVisibleServiceFee(bps: number | null | undefined): bps is number {
  return typeof bps === "number" && bps > 0;
}

/**
 * `bps` (350 = 3.5%) → «3.5%». Без `Intl` — `bps` целое от 0 до 10000
 * (`restaurants.service_fee_bps` CHECK), значит `bps / 100` даёт максимум два
 * знака после запятой, и обычный `toFixed(2)` с обрезкой хвостовых нулей даёт
 * ровно то же число, что `Intl.NumberFormat` дал бы для процента, без риска
 * получить другую локаль на сборке без полного ICU (та же причина, что у
 * `formatMoneyMinor` в `apps/mobile/src/lib/format.ts`).
 *
 * Вызывать только когда `hasVisibleServiceFee` вернула true — «0%» сам по
 * себе не запрещённая строка, но экран не должен её печатать.
 */
export function formatServiceFeePercent(bps: number): string {
  const percent = bps / 100;
  const text = percent.toFixed(2).replace(/\.?0+$/, "");
  return `${text}%`;
}
