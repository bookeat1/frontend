"use client";

import { webCuisineTile, webLayout } from "@bookeat/design-tokens";
import type { Cuisine } from "@bookeat/api/client";

import { CuisineTile } from "@web/components/home/CuisineTile";

/**
 * Ряд «Выберите кухню» — Figma 3254:6.
 *
 * ГЛАВНОЕ ПРАВИЛО РЯДА: он ОДНА строка, без переноса и без прокрутки
 * (замечание владельца 01.09.2026). В макете кухонь десять и они разложены
 * `space-between` по 1200; справочник на тестовом стенде отдаёт четырнадцать.
 * Обе прежние попытки были неверны: `flex-wrap` переносил ряд на вторую
 * строку, `overflow-x-auto` прятал часть кухонь за прокруткой.
 *
 * Поэтому ряд — сетка из РОВНО стольких колонок, сколько кухонь пришло:
 * `repeat(N, minmax(0, 1fr))`. Колонка делит между собой всю ширину, кружок
 * тянется на колонку и упирается в 104 из макета. При N = 10 колонка выходит
 * 103,5 — то есть на данных макета ряд совпадает с макетом; при N = 14 колонка
 * 71,8, и кружки мельче нарисованных. Это осознанный размен: показать все
 * кухни целиком важнее, чем сохранить диаметр (кухня — это вход в фильтр
 * каталога, спрятанный вход гость не восстановит).
 *
 * `minmax(0, 1fr)`, а не `1fr`: у `1fr` минимум равен `auto`, то есть ширине
 * самого длинного слова подписи, и «Средиземноморская» вытолкнула бы сетку за
 * пределы контейнера — ровно тот же переполненный ряд, только без прокрутки.
 *
 * НИЖЕ 1024 сетка выключается и возвращается прокрутка. Четырнадцать колонок
 * на 360 px дают кружок в 10 px и подпись в один столбец букв — это не «одна
 * строка», а нечитаемая полоса. Прокрутка вбок на телефоне привычна и ничего
 * не прячет безвозвратно; на десктопе, где владелец и смотрит, её нет.
 * `gridTemplateColumns` в `style` при `display: flex` просто не действует,
 * поэтому переключение — один класс, без второй ветки разметки.
 */
export function CuisineRow({ items }: { items: readonly Cuisine[] }) {
  const columns = Math.max(items.length, 1);

  // Ширина колонки при контейнере 1200 и просвете из макета. Считается, а не
  // подбирается: как только колонка становится уже нарисованного кружка,
  // подпись 16/18 в неё перестаёт помещаться и переходит на мелкий кегль.
  const columnWidth =
    (webLayout.containerWidth - (columns - 1) * webCuisineTile.rowGapX) / columns;
  const compact = columnWidth < webCuisineTile.size;

  return (
    // Число колонок приходит из ДАННЫХ, поэтому оно в `style`, а не классом:
    // статического имени утилиты для «столько колонок, сколько кухонь» нет.
    <ul
      className="flex list-none items-start gap-x-cuisine-row-x overflow-x-auto pb-2 lg:grid lg:overflow-x-visible lg:pb-0"
      style={{ gridTemplateColumns: `repeat(${columns}, minmax(0, 1fr))` }}
    >
      {items.map((cuisine) => (
        <li key={cuisine.id} className="w-cuisine shrink-0 lg:w-full lg:min-w-0">
          <CuisineTile cuisine={cuisine} compact={compact} />
        </li>
      ))}
    </ul>
  );
}
