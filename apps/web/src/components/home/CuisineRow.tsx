"use client";

import { webCuisineTile, webLayout } from "@bookeat/design-tokens";
import type { Cuisine } from "@bookeat/api/client";

import { CuisineTile } from "@web/components/home/CuisineTile";
import { cx } from "@web/lib/cx";

/**
 * Ряд «Выберите кухню» — Figma 3254:6.
 *
 * Ряд ОДНОСТРОЧНЫЙ и показывает ВСЕ кухни справочника (решение владельца
 * 01.09.2026: «показывай все 14, давай попробуем уменьшить шрифт»). В макете
 * кухонь десять и они разложены `space-between` по 1200; справочник отдаёт
 * четырнадцать.
 *
 * ЯЧЕЙКА ТЯНЕТСЯ ПО ПОДПИСИ — ровно как в макете, где три соседние ячейки
 * имеют ширину 104, 112 и 122 при одном и том же круге 104. Технически это
 * `width: min-content`: ширина ячейки равна ширине САМОГО ДЛИННОГО СЛОВА
 * подписи (или круга, если слово короче). Отсюда два нужных свойства сразу:
 *
 *   • слово никогда не рвётся — ячейка всегда не уже слова;
 *   • название из нескольких слов («Еуропалық асхана») переносится ПО
 *     ПРОБЕЛУ, а не растягивает ряд на всю свою длину.
 *
 * Прежняя сетка из равных колонок (`repeat(N, minmax(0, 1fr))`) этого не
 * умела: при четырнадцати кухнях колонка выходит (1200 − 13 × 15) / 14 = 71,8,
 * а «Средиземноморская» просит в ней кегль 6,6 — то есть колонка была
 * достижима только ценой разрыва слова. Теперь короткие названия отдают
 * лишнее длинным, и на весь ряд хватает кегля 11 (`labelFontSizeCompact`).
 *
 * ПРОКРУТКА ОСТАЁТСЯ ЗАПАСНЫМ ВЫХОДОМ, а не режимом по умолчанию. Замерено
 * в Chromium на живом справочнике: на 1440 ряд занимает 1127 из 1200 и полосы
 * прокрутки нет, на 1280 — 1127 из 1152, тоже нет. Ниже 1175 ряд не помещается
 * ни при каком читаемом кегле (976 доступных на 1024 против 1127 нужных),
 * и там он честно прокручивается — вместе с подписью размера макета, потому
 * что мелкий кегль в прокручиваемом ряду ничего не спасает.
 */
export function CuisineRow({ items }: { items: readonly Cuisine[] }) {
  // Тесно или нет — считается из макета, а не порогом «от одиннадцати штук»:
  // ряд из N кругов по 104 с просветами 15 просто не влезает в 1200 при
  // N ≥ 11 (десять дают 1175, одиннадцать — 1294).
  const designRowWidth =
    items.length * webCuisineTile.size + (items.length - 1) * webCuisineTile.rowGapX;
  const compact = designRowWidth > webLayout.containerWidth;

  return (
    <ul
      className={cx(
        // `justify-between` — это раскладка макета. Просвет в `gap-x` при этом
        // работает НИЖНЕЙ ГРАНИЦЕЙ: пока ряд помещается, браузер разводит
        // ячейки шире, а когда не помещается — включается прокрутка.
        //
        // `-m-1 p-1` — не отступ, а место для рамки фокуса: `overflow-x: auto`
        // делает `overflow-y` тоже `auto`, и обводка ячейки (2 px с отбивкой
        // 2 px) без этих четырёх пикселей срезалась бы сверху. Отрицательное
        // поле возвращает ряд на исходное место, так что вёрстка не едет.
        "-m-1 flex list-none items-start gap-x-cuisine-row-x overflow-x-auto p-1 xl:justify-between",
        compact && "xl:gap-x-cuisine-row-x-compact",
      )}
    >
      {items.map((cuisine) => (
        // `w-min` = `width: min-content`. `shrink-0`, иначе флекс ужмёт ячейку
        // ниже её минимума и слово снова начнёт рваться.
        <li key={cuisine.id} className="w-min shrink-0">
          <CuisineTile cuisine={cuisine} compact={compact} />
        </li>
      ))}
    </ul>
  );
}
