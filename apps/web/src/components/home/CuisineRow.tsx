"use client";

import { CuisineTile } from "@web/components/home/CuisineTile";
import { Skeleton } from "@web/components/state/AsyncBlock";
import type { Cuisine } from "@bookeat/api/client";

/**
 * Класс полосы прокрутки — один на ряд и на его скелетон, иначе заглушка и
 * содержимое разъезжаются, и страница прыгает в момент появления данных
 * (так было до 01.09.2026: скелетон рисовал сетку из десяти колонок).
 *
 * `-m-1 p-1` — не отступ, а место для рамки фокуса: `overflow-x: auto` делает
 * `overflow-y` тоже `auto`, и обводка ячейки (2 px с отбивкой 2 px) без этих
 * четырёх пикселей срезалась бы сверху. Отрицательное поле возвращает ряд на
 * исходное место, так что первый кружок стоит ровно под заголовком секции, а
 * не сдвинут на 4 px.
 *
 * Отступы по краям ряду даёт `Container`: ниже 1440 это `px-4`/`lg:px-6`, на
 * 1440 и шире — поля страницы 120 px по обе стороны от 1200. Поэтому крайние
 * кружки не липнут к краю окна, а ряд остаётся в одной вертикали с остальной
 * страницей.
 *
 * `overscroll-x-contain` — чтобы горизонтальный свайп по ряду на трекпаде не
 * доводился до жеста «назад» в браузере.
 */
const ROW_CLASS =
  "row-scrollbar -m-1 flex list-none flex-nowrap items-start gap-x-cuisine-row-x " +
  "overflow-x-auto overscroll-x-contain p-1 motion-safe:scroll-smooth";

/**
 * Ряд «Выберите кухню» — Figma 3254:6, кадр 3253:2.
 *
 * РЯД ПРОКРУЧИВАЕТСЯ ВБОК НА ЛЮБОЙ ШИРИНЕ. Решение владельца 01.09.2026:
 * «в мобильном приложении они скроллятся, на вебе надо сделать так же».
 * До этого несколько часов действовало обратное требование — уместить весь
 * справочник в одну строку без прокрутки, — и ради него круг ужимали со 104
 * до 64, а подпись с 16 до 11. Прокрутка снимает эту причину целиком, поэтому
 * размеры вернулись к макету: круг 104, подпись 16/18 Medium, просвет 15.
 *
 * Почему без прокрутки не выходило (чтобы никто не попробовал заново):
 * подпись рвать нельзя, значит самое длинное СЛОВО обязано поместиться в
 * ячейку целиком. Замерено в Chromium на живом справочнике из пятнадцати
 * кухонь: ячейки занимают 1643 px («Средиземноморская» одна просит 164),
 * просветы — 14 × 15 = 210, итого ряд 1861 против 1200 у контейнера. Это
 * геометрия, а не подбор значений.
 *
 * ЯЧЕЙКА ТЯНЕТСЯ ПО ПОДПИСИ — ровно как в макете, где три соседние ячейки
 * имеют ширину 104, 112 и 122 при одном и том же круге 104. Технически это
 * `width: min-content`: ширина ячейки равна ширине САМОГО ДЛИННОГО СЛОВА
 * подписи (или круга, если слово короче). Отсюда два нужных свойства сразу:
 *
 *   • слово никогда не рвётся — ячейка всегда не уже слова;
 *   • название из нескольких слов («Еуропалық асхана») переносится ПО
 *     ПРОБЕЛУ, а не растягивает ряд на всю свою длину.
 */
export function CuisineRow({ items }: { items: readonly Cuisine[] }) {
  return (
    <ul className={ROW_CLASS}>
      {items.map((cuisine) => (
        // `w-min` = `width: min-content`. `shrink-0`, иначе флекс ужмёт ячейку
        // ниже её минимума и слово снова начнёт рваться.
        <li key={cuisine.id} className="w-min shrink-0">
          <CuisineTile cuisine={cuisine} />
        </li>
      ))}
    </ul>
  );
}

/**
 * Сколько кружков рисует заглушка.
 *
 * Двенадцать, а не десять из макета, и это не «на глаз»: заглушка обязана
 * ПЕРЕПОЛНЯТЬ ряд так же, как его переполняет настоящий справочник. Десять
 * ячеек по 104 с просветами 15 занимают 1175 из 1200 — полосы прокрутки у
 * такой заглушки нет, а у ряда из пятнадцати кухонь она есть. В браузерах, где
 * полоса классическая и отнимает высоту (не накладывается поверх), это дало бы
 * скачок страницы ровно на высоту полосы в момент прихода данных. Двенадцать
 * ячеек — 12 × 104 + 11 × 15 = 1413 — переполняют ряд на любой ширине,
 * начиная с контейнера 1200.
 *
 * Больше двенадцати не берём: заглушка не должна обещать число кухонь,
 * которого может не быть.
 */
const SKELETON_KEYS = ["a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k", "l"];

/**
 * Заглушка ряда. Высота считается теми же токенами, что и настоящая ячейка
 * (круг 104 + просвет 12 + строка подписи 18 = 134), поэтому появление данных
 * не сдвигает страницу.
 *
 * Чего заглушка НЕ знает — ширины подписей: она рисует ячейки ровно по кругу
 * (104), а настоящие тянутся по самому длинному слову. Горизонтальный сдвиг
 * внутри ряда при появлении данных остаётся; убрать его можно было бы только
 * зная названия заранее.
 */
export function CuisineRowSkeleton() {
  return (
    <ul className={ROW_CLASS}>
      {SKELETON_KEYS.map((key) => (
        <li key={key} className="flex w-cuisine shrink-0 flex-col items-center gap-cuisine-gap">
          <Skeleton className="h-cuisine w-cuisine rounded-full" />
          <Skeleton className="h-cuisine-label w-full" />
        </li>
      ))}
    </ul>
  );
}
