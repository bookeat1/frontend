import { useMemo } from "react";
import { encode } from "uqr";

import { cx } from "@web/lib/cx";

/**
 * QR-код брони (узел 3525:15048 файла QovvuAoI9YxsLMwWkfgKN8).
 *
 * В МАКЕТЕ ЭТО НЕ КАРТИНКА. Код нарисован сорока восемью прямоугольниками
 * 8×8 внутри рамки 96×96 — то есть художник изобразил QR, а не приложил его.
 * Значит генерировать его обязан фронт.
 *
 * БИБЛИОТЕКА — `uqr` (MIT, 84 КБ в node_modules, ноль зависимостей, ESM+CJS).
 * Из трёх ходовых она единственная, которая отдаёт СЫРУЮ МАТРИЦУ
 * (`boolean[][]`) и не тащит за собой ни canvas, ни DOM: `qrcode` рисует на
 * canvas и тянет Node-зависимости в браузерный бандл, `react-qr-code` тянет
 * собственный React-слой ради того же самого. Матрица нужна именно потому,
 * что в макете это прямоугольники: их мы и рисуем.
 *
 * ПОЧЕМУ SVG, А НЕ CANVAS: код должен печататься и масштабироваться (гость
 * покажет его с телефона, сотрудник — отсканирует), а canvas при увеличении
 * рассыпается. И SVG отдаётся сервером в разметке, без ожидания скрипта.
 *
 * УРОВЕНЬ КОРРЕКЦИИ `M`, а не `L` по умолчанию: код показывают с экрана и
 * с бумаги, где четверти площади легко не хватает — блик, палец, сгиб.
 *
 * СВЕТЛОЕ ПОЛЕ РИСУЕТ НЕ SVG, а рамка вокруг него (`bg-canvas` узла
 * 3525:15048): цвет фона — это токен сайта, и повторять его шестнадцатеричным
 * числом внутри картинки значило бы завести второй источник правды о белом.
 *
 * ДОСТУПНОСТЬ: у картинки роль `img` и подпись, потому что содержимое кода
 * (идентификатор брони) диктору бесполезно, а «графика без подписи» — это
 * дырка в озвучке карточки. Сам код продублирован рядом текстом (узел
 * 3525:15101), поэтому потери информации нет.
 */
export function QrCode({
  value,
  label,
  className,
}: {
  /** Что зашито в код. Пустая строка — кода нет вовсе. */
  value: string;
  /** Подпись для скринридера. */
  label: string;
  className?: string;
}) {
  const rows = useMemo(() => (value ? runsOf(value) : null), [value]);
  if (!rows) return null;

  return (
    <svg
      role="img"
      aria-label={label}
      viewBox={`0 0 ${rows.size} ${rows.size}`}
      // Растр НЕ сглаживаем: размытый модуль читается сканером хуже чёткого.
      shapeRendering="crispEdges"
      // Размер задаёт родитель — рамка 96×96 с обводкой (узел 3525:15048):
      // фиксированный размер здесь спорил бы с её паддингом.
      className={cx("block h-full w-full", className)}
    >
      {rows.runs.map((run) => (
        <rect
          key={`${run.y}-${run.x}`}
          x={run.x}
          y={run.y}
          width={run.width}
          height={1}
          fill="currentColor"
        />
      ))}
    </svg>
  );
}

interface Run {
  x: number;
  y: number;
  width: number;
}

/**
 * Матрица → горизонтальные полосы.
 *
 * Модуль на модуль дал бы под тысячу узлов `<rect>` на код версии 2 — столько
 * же операций разметки при каждой перерисовке страницы. Соседние тёмные
 * модули одной строки — это один прямоугольник, и картинка получается
 * пиксель в пиксель та же. Стоит это один проход по матрице, O(n²) по стороне
 * кода, то есть сотни операций один раз на монтирование.
 */
function runsOf(value: string): { size: number; runs: Run[] } {
  const { size, data } = encode(value, { ecc: "M", border: 1 });
  const runs: Run[] = [];
  for (let y = 0; y < size; y += 1) {
    const row = data[y];
    let start = -1;
    for (let x = 0; x <= size; x += 1) {
      const dark = x < size && row[x] === true;
      if (dark && start === -1) start = x;
      if (!dark && start !== -1) {
        runs.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  }
  return { size, runs };
}
