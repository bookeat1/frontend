import type { ReactNode } from "react";

import { cx } from "@web/lib/cx";

/**
 * Оболочка попапа под полем: белая подложка с той же тенью, что у панели
 * поиска (`shadow-panel`, узел 3253:36), радиус 20 (`rounded-panel`) — оба
 * токена переиспользованы, а не подобраны заново. Позиционирование
 * `absolute` под полем; `className` задаёт ширину/паддинг под конкретный
 * попап (календарь, колесо времени/гостей на панели поиска, календарь
 * карточки брони). `max-w-[calc(100vw-32px)]` не даёт попапу вылезти за
 * экран 360 px.
 *
 * Вынесено из `SearchPanel` (был локальной функцией) в задаче «нативный
 * календарь на карточке брони» (2026-09-14): второй, чуть другой попап на
 * карточке заведения был бы тем же дефектом, что вторая кнопка — общая
 * подложка нужна ОБОИМ местам, где уже стоит `Calendar`.
 * Паддинг НЕ задан здесь: `cx` — простая склейка без tailwind-merge (см.
 * `@web/lib/cx`), так что `p-*` в базе и переопределение в `className` могли
 * бы конфликтовать по порядку в сгенерированном CSS, а не по порядку в
 * строке класса. Поэтому паддинг явный на каждом месте использования.
 */
export function Popover({
  className,
  align = "center",
  children,
}: {
  className?: string;
  /** `center` — под серединой поля (панель поиска, широкая строка);
   * `start` — прижат к левому краю поля (узкая колонка карточки брони, где
   * центрирование увело бы попап за правый край колонки). */
  align?: "center" | "start";
  children: ReactNode;
}) {
  return (
    <div
      className={cx(
        "absolute top-full z-20 mt-2 max-w-[calc(100vw-32px)] rounded-panel border border-line-control bg-canvas shadow-panel",
        align === "center" ? "left-1/2 -translate-x-1/2" : "left-0",
        className,
      )}
    >
      {children}
    </div>
  );
}
