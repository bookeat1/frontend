import type { ImageLoaderProps } from "next/image";

/**
 * Загрузчик картинок для `next/image`.
 *
 * Адреса фотографий приходят из БД: боевой бакет R2 (`pub-…r2.dev`), старые
 * ссылки на Supabase Storage и вставленные руками URL. Перечислить эти домены
 * в `images.remotePatterns` нельзя — новая ссылка ломалась бы молча, а
 * `hostname: "**"` превратил бы наш сервер в открытый оптимизатор чужих
 * картинок (за него платим мы, и через него ходят чужие запросы).
 *
 * Поэтому загрузчик отдаёт адрес КАК ЕСТЬ: оптимизации размера нет, но
 * остаётся всё остальное, ради чего нужен `next/image` — ленивая загрузка,
 * зарезервированное место под картинку (никакого скачка вёрстки), `sizes` и
 * атрибуты декодирования. Ровно та же причина, по которой обычный <img>
 * используется в apps/admin/src/components/ui/ImageThumb.tsx.
 */
export default function imageLoader({ src }: ImageLoaderProps): string {
  return src;
}
