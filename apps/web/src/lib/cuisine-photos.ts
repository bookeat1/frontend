import { assetUrl } from "@web/lib/asset";

/**
 * ЗАПАСНЫЕ снимки для кругов «Выберите кухню».
 *
 * Основной источник — справочник: `GET /cuisines` отдаёт `image_url`, и круг
 * рисует его. Но поле необязательное, и на тестовом стенде его нет НИ У ОДНОЙ
 * записи — проверено запросом 2026-08-30 (14 записей) и 2026-09-01 (15, после
 * добавления «Индийской»). На бою на 2026-08-30 ссылки были у четырёх из
 * четырнадцати. Без запасного снимка ряд превращается в строй пустых серых
 * кругов, что владелец и увидел на стенде.
 *
 * Порядок источников (см. CuisineTile):
 *   1. `cuisine.imageUrl` из справочника;
 *   2. снимок отсюда по КОДУ кухни — если ссылки нет ИЛИ она не загрузилась
 *      (битая ссылка для гостя выглядит ровно как отсутствующая);
 *   3. монограмма — первая буква названия на фирменной подложке.
 *
 * Файлы — те же картинки, что лежат в `apps/mobile/assets/cuisines`
 * (в основном экспорты из макета, Figma node 3106:12265), уменьшенные до
 * 208×208 (2× круга 104) и переведённые в webp: ~200 КБ на все шестнадцать
 * вместо 2,1 МБ исходников. ДОЛГ: сейчас это ВТОРАЯ копия одних и тех же
 * картинок в репозитории. Общего места для бинарных ассетов у монорепозитория
 * нет (`design-tokens` — чистый TypeScript), заводить его ради шестнадцати
 * файлов в рамках правки вёрстки не стали.
 *
 * Ключи — коды справочника: `mapCuisine` кладёт в `Cuisine.id` именно `code`
 * (латиница). С 02.09.2026 свой снимок есть у ВСЕХ пятнадцати кодов: трём
 * последним — `georgian`, `authors` и `indian` — картинки взяты из мобильных
 * ассетов (добавлены туда 01.09.2026, CC0 с Викисклада, источники перечислены
 * в шапке `apps/mobile/src/components/explore/cuisine-photos.ts`), чтобы
 * приложение и сайт показывали кухню одним и тем же кадром. В макете этих трёх
 * кухонь по-прежнему нет. Монограмма осталась ТОЛЬКО как запас на будущее:
 * шестнадцатый код справочника до своей картинки покажет букву, а не пустой
 * круг.
 *
 * РАСХОЖДЕНИЕ, оставленное сознательно: у `japanese` и `pan_asian` веб рисует
 * экспорт из макета (узлы 3254:16 и 3254:19), а мобильное приложение — кадры с
 * Викисклада, добавленные 01.09.2026. По правилу «всегда по макету» правильная
 * сторона — веб; выравнивать надо мобильные ассеты, а не наоборот.
 */

/** Имя файла отличается от кода только у «Восточной»: `oriental` → eastern. */
const FILES: Record<string, string> = {
  european: "european",
  mediterranean: "mediterranean",
  seafood: "seafood",
  kazakh: "kazakh",
  italian: "italian",
  turkish: "turkish",
  french: "french",
  greek: "greek",
  oriental: "eastern",
  vegan: "vegan",
  // Добавлено 31.08.2026: снимки этих двух кухонь В МАКЕТЕ ЕСТЬ (узлы 3254:16
  // и 3254:19 кадра 3253:2), просто раньше их не экспортировали — и оба круга
  // показывали монограмму. Экспорт из тех же заливок, что и остальные.
  japanese: "japanese",
  pan_asian: "pan_asian",
  // Добавлено 02.09.2026 из мобильных ассетов (там CC0-кадры с Викисклада,
  // 288×288), пережаты в 208×208 webp как остальные: до этого все три круга
  // показывали монограмму, что владелец и увидел на скриншоте.
  georgian: "georgian",
  authors: "authors",
  indian: "indian",
  // Кода `bakery` в справочнике нет, но файл из макета есть: заведению со
  // старой текстовой кухней «Пекарня» id считается как casefold названия.
  bakery: "bakery",
  пекарня: "bakery",
};

export function cuisinePhoto(cuisineId: string): string | undefined {
  const file = FILES[cuisineId.trim().toLowerCase()];
  // Префикс раздачи приписывает `assetUrl` — см. комментарий там.
  return file ? assetUrl(`/cuisines/${file}.webp`) : undefined;
}
