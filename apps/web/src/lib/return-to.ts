/**
 * Куда вернуть гостя после входа.
 *
 * Адрес возврата приходит ПАРАМЕТРОМ АДРЕСНОЙ СТРОКИ, то есть местом, куда кто
 * угодно может написать что угодно. Поэтому он не подставляется в переход как
 * есть: `/login?next=https://evil.example` увёл бы гостя на чужой сайт сразу
 * после ввода кода — это открытый редирект, классика фишинга: гость уверен,
 * что идёт по кнопке BookEat.
 *
 * Пропускаем ТОЛЬКО путь внутри сайта. Разбор строгий, потому что «начинается
 * со слэша» — недостаточное условие:
 *
 *   `//evil.example`  протокольно-относительный адрес: браузер откроет
 *                     `https://evil.example`, хотя слэш в начале есть;
 *   `/\evil.example`  то же самое — обратный слэш при разборе схемы браузеры
 *                     приравнивают к прямому;
 *   пробелы и управляющие символы браузер выбрасывает ПЕРЕД разбором, поэтому
 *                     строка вида `/<таб>/evil.example` снова превращается в
 *                     `//evil.example` уже после любой нашей проверки.
 *
 * Всё, что не прошло, молча превращается в главную: спорить с гостем не о чем,
 * а падать на подделанной ссылке тем более незачем.
 */

/** Имя параметра. Одно на весь сайт: разъедутся — возврат молча перестанет работать. */
export const RETURN_PARAM = "next";

/** Куда идём, если адрес возврата не задан или не прошёл проверку. */
const HOME = "/";

/** Пробелы и управляющие символы (включая экзотику вроде U+2028) — адрес с
 * ними браузер увидит не таким, каким его проверили, поэтому не чиним, а
 * отвергаем целиком. */
const UNSAFE_CHARS = /[\u0000-\u0020\u007f-\u009f\u2000-\u200f\u2028-\u202f\u205f-\u206f\u3000\ufeff]/;

export function safeReturnPath(raw: string | null | undefined): string {
  if (!raw) return HOME;
  if (UNSAFE_CHARS.test(raw)) return HOME;

  // Ровно один слэш в начале и никакого второго слэша или обратного слэша
  // следом. Это отсекает и `//host`, и `/\host`, и любой абсолютный адрес со
  // схемой (`https://…` не начинается со слэша вовсе).
  if (!raw.startsWith("/") || raw.startsWith("//") || raw.startsWith("/\\")) return HOME;

  return raw;
}

/**
 * Адрес экрана входа с возвратом на `path`.
 *
 * Путь проверяется ЗДЕСЬ ЖЕ, а не только на выходе: незачем класть в ссылку
 * то, что на другом конце всё равно будет отброшено.
 */
export function loginHref(path: string): string {
  const target = safeReturnPath(path);
  if (target === HOME) return "/login";
  return `/login?${RETURN_PARAM}=${encodeURIComponent(target)}`;
}

/**
 * Текущий адрес страницы для возврата — только в обработчике события.
 *
 * Читает `window.location`, поэтому его результат не должен попадать в
 * разметку (в `href` ссылки): на сервере строки поиска нет, и разметка
 * разошлась бы с той, что React соберёт в браузере. Для ссылок берём
 * `usePathname()` — он одинаков на обеих сторонах.
 */
export function currentPathForReturn(): string {
  if (typeof window === "undefined") return HOME;
  return `${window.location.pathname}${window.location.search}`;
}
