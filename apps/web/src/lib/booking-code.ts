/**
 * Код брони на экране успеха.
 *
 * ЧТО НАРИСОВАНО И ЧЕГО НЕТ. В макете (узел 3525:15101) стоит `BE-4821-KZ`, а
 * рядом QR из 48 прямоугольников. У бэкенда НЕТ поля «код брони»: у брони есть
 * только `id` — UUID (`internal/transport/rest/bookings/response.go`). Значит
 * выбор был между тремя вариантами:
 *
 *   1. напечатать UUID целиком — правда, но продиктовать его на входе нельзя;
 *   2. придумать отдельный короткий код на клиенте — тогда одна и та же бронь
 *      получала бы РАЗНЫЙ код в разных браузерах, и он ничего не значил бы;
 *   3. вывести код ИЗ идентификатора детерминированно — так, что по коду
 *      однозначно узнаётся начало UUID, а по UUID — код.
 *
 * Взят третий: `BE-` плюс первые восемь шестнадцатеричных знаков `id`
 * заглавными, разбитые пополам. Формат макета (`BE-4821-KZ`) сохранён по духу,
 * но суффикс «KZ» убран: он не несёт информации, а место занимает.
 *
 * ЧЕГО ЭТОТ КОД НЕ УМЕЕТ, и это названо владельцу отдельной строкой: искать
 * бронь по нему сегодня негде. В кабинете заведения поиска по броням нет
 * вовсе (`apps/admin/src/components/BookingsView.tsx` — только фильтр по дате
 * и статусу), сервер ручки «найти бронь по коду» не имеет. Работающая половина
 * подписи макета — «или назовите имя»: имя и телефон гостя заведение видит в
 * своём списке на день. Поэтому QR несёт ПОЛНЫЙ идентификатор, а не короткий
 * код: сканеру нужен ключ, по которому бронь действительно находится.
 */

/** Сколько знаков идентификатора попадает в код. Восемь шестнадцатеричных —
 * это 4 миллиарда значений: на список одного заведения за день с запасом. */
const CODE_LENGTH = 8;

const PREFIX = "BE";

/**
 * `BE-A1B2-C3D4` для идентификатора `a1b2c3d4-…`.
 *
 * `null`, если знаков не хватило: пустой или обрезанный идентификатор — это
 * «сервер не сказал», и печатать «BE--» вместо кода нельзя.
 */
export function bookingCode(id: string): string | null {
  const hex = id.replace(/[^0-9a-fA-F]/g, "").slice(0, CODE_LENGTH).toUpperCase();
  if (hex.length < CODE_LENGTH) return null;
  return `${PREFIX}-${hex.slice(0, 4)}-${hex.slice(4)}`;
}

/**
 * Что зашито в QR — идентификатор брони ДОСЛОВНО, без префиксов и схем.
 *
 * Не ссылка: страница брони на сайте требует сессию гостя, и сотрудник на
 * входе, отсканировав её, увидел бы экран входа, а не бронь. Не короткий код:
 * по нему бронь не ищется (см. заголовок файла). Голый UUID — единственное,
 * что любая будущая сторона сможет разобрать однозначно.
 */
export function bookingQrPayload(id: string): string {
  return id.trim();
}
