/**
 * ЕДИНСТВЕННОЕ место во всём приложении, где называется пакет `expo-haptics`.
 *
 * Обращение к нему обязано быть ленивым (почему — подробно в `haptics.ts`:
 * это новый нативный модуль, а JS мы возим по воздуху в сборки, где его нет).
 * Поэтому импорт стоит ВНУТРИ функции: на загрузке бандла он не выполняется.
 *
 * ЛОВУШКА, ради которой файл отдельный. На нативе `import()` — не то же самое,
 * что в браузере или в Node. Metro превращает его в `asyncRequire`, а тот, пока
 * бандл не разрезан на части (у нас не разрезан — `expo export --platform
 * android` отдаёт один файл), зовёт обычный синхронный `require` и только
 * оборачивает результат в «обещаниеподобный» объект:
 *
 *     var u = () => r.importAll(moduleId);
 *     var l = __loadBundleAsync ? … : undefined;      // undefined без сплита
 *     return l != null ? l.then(u) : u();             // ← синхронный вызов
 *
 * Значит отказ модуля прилетит НЕ отказом обещания, а броском прямо из этой
 * функции, ещё до того, как к обещанию успеют прицепить `.catch`. Отсюда её
 * контракт: тип возврата — `Promise`, но вызывать её можно только внутри
 * `try/catch`. Единственный вызывающий — `loadHaptics()` в `haptics.ts`, там
 * это и сделано.
 */

/** Ровно то, чем пользуемся. Тип берётся у настоящего пакета, но стирается. */
export type HapticsModule = Pick<
  typeof import("expo-haptics"),
  "selectionAsync" | "performAndroidHapticsAsync" | "AndroidHaptics"
>;

/** Подтянуть нативный модуль. Может бросить синхронно — см. комментарий выше. */
export function importHaptics(): Promise<HapticsModule> {
  return import("expo-haptics");
}
