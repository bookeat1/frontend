import { describe, expect, it } from "vitest";
import { countryByIso2, DEFAULT_COUNTRY } from "../countries";
import {
  formatNational,
  isPhoneComplete,
  parsePhoneInput,
  toE164,
  type PhoneValue,
} from "../phone";

/**
 * REGRESSION GUARD — одно и то же поле телефона вело себя тремя разными
 * способами, и вставленный номер ломался в каждом.
 *
 * Что было до этого файла (проверено чтением кода на develop d789f88):
 *
 *   - ЭКРАН ВХОДА. Жёсткая маска «+7», префикс нарисован отдельно, а цифры
 *     чистились функцией `extractNationalDigits`, которая обрезала ввод до
 *     ДЕСЯТИ цифр. Вставка «+1 212 555 1234» превращалась в «+7 (121)
 *     255-51-23» — номер, который никому не принадлежит, и код ушёл бы на
 *     него. Иностранец не мог войти вообще: аккаунт заводится по номеру
 *     (`users.GetByPhone` → `users.Create`), значит без своего номера у него
 *     нет и аккаунта.
 *
 *   - ФОРМА БРОНИ. Маски не было вовсе — намеренно, потому что иностранный
 *     номер там законен, заведение просто звонит по нему. Но вместе с маской
 *     не было и страны: гость набирал «2125551234», сервер нормализовал это в
 *     «+72125551234» (`internal/auth/phone.Normalize`: десять цифр ⇒ «+7» +
 *     цифры), и заведению доставался казахстанский номер вместо американского.
 *
 *   - ПРОФИЛЬ. Третье поведение — показ, разобранный в phone-display.test.ts.
 *
 * Здесь проверяется разбор ввода: он один на все три экрана, и именно в нём
 * жила разница. Границы, а не середина: длина ровно на цифру короче и ровно на
 * цифру длиннее допустимой, и «мы не знаем формат» как отдельный исход, а не
 * как разновидность отказа.
 */

const KZ = DEFAULT_COUNTRY;
const US = countryByIso2("US")!;
const GB = countryByIso2("GB")!;

/** Короткая запись результата: страна + национальные цифры. */
function shape(v: PhoneValue): string {
  return `${v.country.iso2}:${v.national}`;
}

describe("вставка номера в поле", () => {
  it("«+7 701 234 56 78» — казахстанский номер с кодом и пробелами", () => {
    expect(shape(parsePhoneInput("+7 701 234 56 78", KZ))).toBe("KZ:7012345678");
    expect(toE164(parsePhoneInput("+7 701 234 56 78", KZ))).toBe("+77012345678");
  });

  it("«87012345678» — домашняя запись через восьмёрку", () => {
    expect(shape(parsePhoneInput("87012345678", KZ))).toBe("KZ:7012345678");
    expect(toE164(parsePhoneInput("87012345678", KZ))).toBe("+77012345678");
  });

  it("«7 (701) 234-56-78» — код страны без плюса, со скобками", () => {
    expect(shape(parsePhoneInput("7 (701) 234-56-78", KZ))).toBe("KZ:7012345678");
  });

  it("«+1 212 555 1234» — американский номер сам переключает страну", () => {
    const v = parsePhoneInput("+1 212 555 1234", KZ);
    expect(shape(v)).toBe("US:2125551234");
    expect(toE164(v)).toBe("+12125551234");
    // Тот самый провал старого поля: ни одной «+7»-интерпретации.
    expect(toE164(v)).not.toContain("+7");
  });

  it("американский номер БЕЗ плюса тоже опознаётся, а не становится казахстанским", () => {
    // Одиннадцать цифр, начинаются не с 7 и не с 8 — местным номером быть не
    // могут. Раньше форма брони отправляла их как есть, и сервер делал «+7…».
    expect(shape(parsePhoneInput("12125551234", KZ))).toBe("US:2125551234");
  });

  it("уже нормализованный E.164 разбирается обратно без потерь", () => {
    // Так в поле приезжает предзаполнение из аккаунта и восстановленный
    // черновик брони: значение обязано пережить круг.
    for (const e164 of ["+77012345678", "+12125551234", "+998901234567"]) {
      expect(toE164(parsePhoneInput(e164, KZ))).toBe(e164);
    }
  });
});

describe("набор номера руками", () => {
  it("страна не съезжает, пока номер помещается в текущую", () => {
    // Главное требование к быстрому набору: селектор не двигается под пальцами.
    let acc = "";
    for (const digit of "7012345678") {
      acc += digit;
      expect(parsePhoneInput(acc, KZ).country.iso2).toBe("KZ");
    }
  });

  it("восьмёрка в начале снимается сразу, а не на одиннадцатой цифре", () => {
    // Иначе гость смотрит, как маска рисует «(870) 123-45-6», и только на
    // последней цифре всё перестраивается.
    expect(shape(parsePhoneInput("8", KZ))).toBe("KZ:");
    expect(shape(parsePhoneInput("87", KZ))).toBe("KZ:7");
    expect(shape(parsePhoneInput("8701", KZ))).toBe("KZ:701");
  });

  it("выделить всё и напечатать заново — поле берёт новый ввод целиком", () => {
    // Разбор идёт от всей строки, а не от разницы с предыдущей, поэтому
    // замена десяти цифр одной работает так же, как ввод с нуля.
    expect(shape(parsePhoneInput("5", KZ))).toBe("KZ:5");
  });

  it("лишние цифры сверх формата страны не попадают в поле", () => {
    // Граница: ровно десять — можно, одиннадцатая уже нет (её съел бы разбор
    // кода страны, и номер поехал бы).
    expect(parsePhoneInput("70123456789", KZ).national.length).toBe(10);
  });
});

describe("страна, формата которой мы не знаем", () => {
  it("принимает свободные цифры, а не отказывается их брать", () => {
    // Это прямое требование: незнание таблицы не должно мешать человеку ввести
    // настоящий номер. У Великобритании формат не заявлен.
    const v = parsePhoneInput("2071838750", GB);
    expect(shape(v)).toBe("GB:2071838750");
    expect(toE164(v)).toBe("+442071838750");
  });

  it("считается заполненной по нижней границе длины, а не по выдуманному шаблону", () => {
    expect(isPhoneComplete({ country: GB, national: "20718" })).toBe(true);
    expect(isPhoneComplete({ country: GB, national: "2" })).toBe(false);
  });
});

describe("готовность номера к отправке", () => {
  it("для страны с известным форматом — ровно столько цифр, сколько в нём", () => {
    expect(isPhoneComplete({ country: KZ, national: "701234567" })).toBe(false); // 9
    expect(isPhoneComplete({ country: KZ, national: "7012345678" })).toBe(true); // 10
    expect(isPhoneComplete({ country: US, national: "2125551234" })).toBe(true);
  });

  it("пустое поле не даёт «+7» вместо номера", () => {
    // «+7» само по себе — не номер, и уйти на сервер как номер не может.
    expect(toE164({ country: KZ, national: "" })).toBe("");
  });
});

describe("маска на экране", () => {
  it("растёт вместе с вводом и ставит скобку только на полной группе", () => {
    expect(formatNational("70", KZ)).toBe("(70");
    expect(formatNational("701", KZ)).toBe("(701)");
    expect(formatNational("7012", KZ)).toBe("(701) 2");
    expect(formatNational("7012345678", KZ)).toBe("(701) 234-56-78");
  });

  it("у каждой страны своя группировка, а не казахстанская для всех", () => {
    expect(formatNational("2125551234", US)).toBe("(212) 555-1234");
    expect(formatNational("901234567", countryByIso2("UZ")!)).toBe("(90) 123-45-67");
    // Формат неизвестен — цифры как есть, без выдуманных скобок.
    expect(formatNational("2071838750", GB)).toBe("2071838750");
  });
});
