import { Platform } from "react-native";
import { type HapticsModule, importHaptics } from "./haptics-native";

/**
 * Короткий тактильный «щелчок» — тот, что даёт системный барабан выбора, когда
 * под центром проходит очередное значение.
 *
 * Правка владельца 2026-09-01: «добавь микровибрацию как в нативках при скроле
 * даты и количества гостей».
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ ИМПОРТ `expo-haptics` ЗДЕСЬ ЛЕНИВЫЙ. НЕ ВОЗВРАЩАТЬ ЕГО НАВЕРХ ФАЙЛА.      │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * `expo-haptics` — НОВЫЙ нативный модуль: его нет ни в одной сборке, которая
 * сейчас стоит у людей (Android 1.5 сборки 100–104 в Google Play, iOS 1.5.1
 * сборка 3 в TestFlight). Он появится только со следующим бинарём.
 *
 * А правки этим сборкам мы возим по воздуху: `eas update` публикуется в том
 * числе под ИХ старые рантаймы (`BOOKEAT_RUNTIME_VERSION=1.5` и `1.5.1`, см.
 * ранбук OTA). То есть свежий JS штатно приезжает на бинарь БЕЗ нативной
 * части этого модуля, и защита «у новой нативки другой отпечаток, обновление
 * ей не достанется» в этом сценарии не работает — мы сами обходим отпечаток.
 *
 * Статический импорт нативного пакета выполняется на ЗАГРУЗКЕ БАНДЛА, до
 * первого экрана. Если такой пакет на старом бинаре падает при вычислении
 * модуля, падает не вибрация — не стартует приложение, сразу у всех, кто
 * получил обновление. `try/catch` на вызове от этого не спасает: он стоит
 * ниже по коду, до него дело не доходит. Поэтому модуль подтягивается ленивым
 * `import()` внутри функции (он один на всё приложение и живёт в
 * `haptics-native.ts`), отказ загрузки запоминается как «модуля нет», и дальше
 * это просто отсутствие вибрации.
 *
 * Отказ приходит в ДВУХ разных видах, и оба погашены: обещание может
 * отказаться, а может — на нативе, где Metro прячет за `import()` обычный
 * синхронный `require`, — броситься прямо на вызове. Первый ловится вторым
 * аргументом `.then`, второй — `try/catch` вокруг него.
 *
 * Честно про конкретно этот пакет: `expo-haptics@57.0.2` внутри зовёт
 * `requireOptionalNativeModule('ExpoHaptics')`, который при отсутствии нативной
 * части возвращает `null`, а не бросает (`node_modules/expo-haptics/src/
 * ExpoHaptics.ts`) — то есть именно он, скорее всего, обошёлся бы и статическим
 * импортом. Проверять это ценой боевого запуска мы не будем, а соседний
 * `requireNativeModule` бросает `Cannot find native module '…'` — так устроено
 * большинство нативных пакетов и прошлые версии этого. Правило дешевле
 * исключения: нативный пакет, добавленный в уже выпущенное приложение,
 * подтягивается лениво.
 *
 * ДВЕ ПЛАТФОРМЫ — ДВА РАЗНЫХ ВЫЗОВА, и это не перестраховка:
 *
 *   iOS — `selectionAsync()`, то есть `UISelectionFeedbackGenerator`. Ровно то,
 *   чем щёлкает `UIPickerView`; ничего короче и мягче в системе нет.
 *
 *   Android — `performAndroidHapticsAsync(Clock_Tick)`, то есть
 *   `View.performHapticFeedback(HapticFeedbackConstants.CLOCK_TICK)` — тик
 *   часового барабана, которым система щёлкает в своих же выборах времени.
 *   НЕ `selectionAsync()`: на Android она уходит в `Vibrator` и играет волну
 *   50 мс амплитудой 30 (см. HapticsSelectionType.kt) — это уже жужжание, а на
 *   быстрой прокрутке несколько таких волн наложатся друг на друга.
 *   `CLOCK_TICK` вдобавок слушается системной настройки тактильного отклика и
 *   не требует разрешения VIBRATE (оно всё равно объявлено манифестом модуля).
 *
 *   `Segment_Frequent_Tick` подошёл бы ещё лучше по смыслу, но эта константа
 *   есть только с Android 14: на всём, что старше, модуль бросает
 *   `HapticsNotSupportedException`, и отклика не было бы вовсе.
 *
 * ТИХО НЕ СРАБОТАТЬ — ЧАСТЬ КОНТРАКТА. Нет вибромотора, выключен тактильный
 * отклик в системе, нет нативной части модуля — обещание не выполняется, и это
 * нормально: вибрация здесь украшение, а не смысл. Поэтому гасится и отказ
 * загрузки модуля, и отказ самого вызова (иначе получаем unhandled rejection на
 * пустом месте), и функция ничего не возвращает — ждать её незачем, прокрутка
 * не должна ждать мотор.
 *
 * На вебе (`expo start --web`, тесты) не делаем НИЧЕГО осознанно: браузерный
 * `navigator.vibrate` — это грубое дребезжание телефона, а не щелчок. Заодно
 * веб вообще не пытается грузить модуль.
 */

/**
 * Результат первой попытки загрузки: `undefined` — ещё не пробовали, `null` —
 * в этой сборке модуля нет.
 *
 * Кэш здесь не про скорость импорта (Metro всё равно отдаёт модуль из того же
 * бандла), а про то, чтобы на прокрутке — до шестидесяти щелчков в секунду —
 * не заводить каждый раз новую цепочку обещаний. После первого щелчка ветка
 * становится синхронной.
 */
let loaded: HapticsModule | null | undefined;
let loading: Promise<HapticsModule | null> | undefined;

function loadHaptics(): Promise<HapticsModule | null> {
  if (loading) return loading;
  try {
    loading = importHaptics().then(
      (haptics) => (loaded = haptics),
      // Модуля в этой сборке нет — запоминаем и больше не пробуем.
      () => (loaded = null),
    );
  } catch {
    // И этот catch не лишний: на нативе Metro выполняет require ВНУТРИ
    // `import()` синхронно, поэтому отсутствующий модуль прилетает броском
    // отсюда, а не отказом обещания. Подробности — в `haptics-native.ts`.
    loaded = null;
    loading = Promise.resolve(null);
  }
  return loading;
}

/** Щёлкнуть тем, что подходит платформе. Ошибка здесь — это просто нет отклика. */
function ring(haptics: HapticsModule | null): void {
  if (!haptics) return;
  try {
    if (Platform.OS === "ios") {
      void haptics.selectionAsync().catch(() => {});
      return;
    }
    void haptics.performAndroidHapticsAsync(haptics.AndroidHaptics.Clock_Tick).catch(() => {});
  } catch {
    // Синхронный отказ нативной привязки не имеет права уронить обработчик
    // прокрутки: колесо крутится дальше, просто молча.
  }
}

export function hapticSelectionTick(): void {
  if (Platform.OS !== "ios" && Platform.OS !== "android") return;
  if (loaded !== undefined) {
    ring(loaded);
    return;
  }
  void loadHaptics().then(ring, () => {});
}
