import type { MenuHighlight } from "@bookeat/api";

/**
 * Лента «Лучшие позиции» на карточке заведения показывает только блюда С
 * ФОТОГРАФИЕЙ.
 *
 * Почему это вообще правило. Карточка ленты — это в первую очередь снимок
 * (180×120 в макете, node 918:11701); блюдо без него превращается в серую
 * плашку с прибором, и ряд из двух таких плашек («Айран 1 л», «Айран 200 мл»
 * на боевом заведении) читается как «витрина сломалась», а не как витрина.
 * В СПИСКЕ меню то же блюдо остаётся на месте: там снимок вторичен, строка
 * несёт название, состав и цену.
 *
 * Это КЛИЕНТСКАЯ страховка, а не источник правила: отбор делает сервер
 * (`GET /restaurants/:id/menu-highlights`). Здесь он повторён, чтобы старая
 * сборка бэкенда не показывала гостю плашки, и убирать его после серверной
 * правки не нужно — двойной отбор ничего не портит.
 *
 * Порядок НЕ трогаем: сервер уже поставил отмеченные заведением блюда вперёд
 * (см. `mapMenuHighlights`). Отбор только выкидывает, не пересортировывает.
 *
 * Признак «фотография есть» — `photo`, а не сама ссылка: маппер уже отличил
 * пустую строку от адреса и кладёт `undefined`, когда снимка нет. Проверка
 * через `Boolean`, а не `!== undefined`: `photo` необязателен, и из чужого
 * кода (тест, будущий маппер, ответ старой сборки) сюда может приехать `null`
 * — «нет фотографии» должно означать одно и то же во всех трёх видах.
 */
export function highlightsWithPhoto(highlights: readonly MenuHighlight[]): MenuHighlight[] {
  return highlights.filter((item) => Boolean(item.photo));
}
