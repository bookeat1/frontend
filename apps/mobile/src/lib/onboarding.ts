/**
 * Что показать сразу после успешного входа по коду — и, главное, КОМУ.
 *
 * Правило владельца (2026-08-26): «если это НОВЫЙ клиент, после входа он
 * попадает на экран даты рождения; существующему не показываем ничего — он
 * правит дату в персональных данных».
 *
 * ЧЕМ «НОВЫЙ» ОПРЕДЕЛЯЕТСЯ, И ЧЕМ НЕ ОПРЕДЕЛЯЕТСЯ
 *
 * Определяется ОТВЕТОМ СЕРВЕРА (`AuthSession.isNewUser`, поле `is_new_user`
 * ответа `POST /auth/otp/verify`). Внутри `completeLogin` бэкенд явно
 * различает «создали» и «нашли» — но наружу сегодня отдаёт только токены,
 * поэтому поле приходит `null`, и это состояние здесь трактуется как «не
 * новый». Пока бэкенд молчит, шаг даты рождения не показывается НИКОМУ: это
 * осознанный выбор в пользу давнего гостя, которому лишний экран регистрации
 * не нужен вовсе.
 *
 * НЕ определяется пустотой профиля. Пустая дата рождения — признак
 * незаполненного поля, а не нового аккаунта: у гостя, который зарегистрировался
 * год назад и просто не стал её вводить, она тоже пустая, и ловить его на
 * экране регистрации нельзя. Пустое имя тоже не признак новизны — это отдельная
 * причина показать шаг имени (имя печатается на каждой брони), и она про поле,
 * а не про возраст аккаунта.
 */

/**
 * МОЖНО ЛИ ПРОПУСТИТЬ шаг даты рождения. Один переключатель на всю фичу —
 * трогать больше нигде ничего не нужно.
 *
 * `true` (решение фронтенда, объяснено владельцу 2026-08-26): в этот момент
 * человек ещё ничего от нас не получил, и обязательное поле сразу после
 * регистрации — надёжный способ потерять регистрацию. Дату всегда можно
 * спросить позже из профиля, где она уже правится календарём.
 *
 * `false` превращает шаг в стену: пропасть будет нечем — ни кнопки
 * «Пропустить», ни стрелки назад, ни аппаратной кнопки Android.
 */
export const BIRTH_DATE_STEP_SKIPPABLE = true;

/** Что из профиля нужно, чтобы принять решение. Намеренно узко — чтобы сюда
 * нельзя было незаметно притащить ещё одну «догадку по пустому полю». */
export interface OnboardingAccount {
  fullName: string;
  birthDate: string | null;
}

export type PostSignInStep = "name" | "birthday" | "none";

/**
 * Куда вести гостя сразу после того, как код принят.
 *
 * `account === null` — это «профиль прочитать не удалось». Тогда «none»: на
 * пустой стене гостя не держим, имя и дату можно заполнить из профиля.
 */
export function postSignInStep(input: {
  isNewUser: boolean | null;
  account: OnboardingAccount | null;
}): PostSignInStep {
  const { isNewUser, account } = input;
  if (!account) return "none";
  // Имя — отдельная, не связанная с новизной причина: оно обязательно и
  // печатается на брони. Этот шаг был здесь и до даты рождения.
  if (account.fullName.trim().length === 0) return "name";
  return birthdayStepFor({ isNewUser, account });
}

/**
 * Нужен ли шаг даты рождения. Вызывается дважды — из экрана входа (когда имя
 * уже есть) и из шага имени (сразу после того, как имя сохранили), — и это
 * одна и та же функция, а не два похожих условия в двух файлах.
 */
export function birthdayStepFor(input: {
  isNewUser: boolean | null;
  account: OnboardingAccount | null;
}): "birthday" | "none" {
  const { isNewUser, account } = input;
  // Строго `=== true`. `null` — это «сервер не сказал», и оно обязано вести
  // себя как «не новый».
  if (isNewUser !== true) return "none";
  // Дата уже есть — спрашивать её ещё раз незачем даже у нового аккаунта
  // (сюда попадает разве что повторный вход в ту же минуту).
  if (account?.birthDate) return "none";
  return "birthday";
}

/** Признак новизны, пережидающий переход между экранами онбординга: он едет
 * параметром маршрута, а не вторым запросом к серверу. */
export function newUserParam(isNewUser: boolean | null): "1" | "0" {
  return isNewUser === true ? "1" : "0";
}

export function parseNewUserParam(raw: string | undefined): boolean | null {
  if (raw === "1") return true;
  if (raw === "0") return false;
  return null;
}
