/**
 * Подпись под кругом кухни: ОДИН кегль для всех, никакого auto-shrink,
 * длинное слово переносится ПО СЛОГУ с дефисом.
 *
 * ИСТОРИЯ. До 2026-09-04 подпись жила с `adjustsFontSizeToFit` +
 * `minimumFontScale`, ширина была зажата шириной круга (96). Итог на
 * скриншотах владельца: «Морепродукты» и «Средиземноморская» рисовались
 * заметно мельче соседей — auto-shrink и есть «разный кегль». Требование
 * владельца: кегль у всех один (14/20 Medium из макета `3447:12763`), каждое
 * название в одну строку шириной по тексту, а единственное исключение —
 * «Средиземноморская» — переносится на вторую строку по слогу:
 * «Средиземно-» / «морская», а не «Средиземноморска» / «я».
 *
 * ПОЧЕМУ ЯВНЫЙ `\n` С ДЕФИСОМ, А НЕ МЯГКИЙ ПЕРЕНОС (U+00AD).
 * Мягкий перенос в React Native НЕ детерминирован:
 *   • Android: RN отдаёт тексту `hyphenationFrequency = none` (по умолчанию,
 *     проп `android_hyphenationFrequency`), а Minikin при `none` не
 *     рассматривает и U+00AD как точку разрыва — символ просто невидим, слово
 *     остаётся неразрывным (или, если ширина зажата, рвётся по букве);
 *   • iOS: TextKit мягкий перенос обычно уважает, но рисует дефис только
 *     когда строка действительно не помещается в контейнер — а мы контейнер
 *     нарочно не ограничиваем (подпись шире круга), так что точки разрыва
 *     платформа не найдёт и перенос не случится вовсе.
 * Явная строка `Средиземно-\nморская` рисуется одинаково на обеих
 * платформах и в react-native-web, проверяется юнит-тестом по строке, и не
 * зависит от того, как платформа меряет ширину. Цена — перенос решается по
 * ДЛИНЕ слова, а не по ширине в точках; для подписи из одного-двух слов это
 * честная модель (см. `MAX_SINGLE_LINE_CHARS`).
 *
 * Названия приходят из справочника `GET /cuisines` и правятся редакцией из
 * кабинета, поэтому словарь — только для известных длинных названий, а всё
 * неизвестное проходит через эвристику `hyphenateWord` (перенос по слогу
 * между гласной и согласной, ближе к середине слова) вместо ужатия шрифта.
 */

/**
 * Сколько символов подписи оставляем в одной строке.
 *
 * Самые длинные названия, которые макет рисует в одну строку, — «Морепродукты»
 * и «Паназиятская», по 12 символов (при 14/20 Medium это ≈100–105 px, чуть
 * шире круга 96 — так и в макете, подпись там hug по тексту). 13 — один
 * символ запаса. От 14 и длиннее слово переносится по слогу; из боевых
 * названий это ровно «Средиземноморская» (17) — единственное исключение,
 * которое владелец разрешил.
 */
export const MAX_SINGLE_LINE_CHARS = 13;

/**
 * Словарь ИЗВЕСТНЫХ длинных названий → их переносная форма. Ключ сравнивается
 * без учёта регистра и пробелов по краям. Явный словарь стоит выше эвристики:
 * для этих слов результат зафиксирован тестом и не поедет, если эвристику
 * когда-нибудь подправят.
 */
const HYPHENATION_DICTIONARY: Readonly<Record<string, string>> = {
  средиземноморская: "Средиземно-\nморская",
  средиземноморские: "Средиземно-\nморские",
  ближневосточная: "Ближне-\nвосточная",
  латиноамериканская: "Латино-\nамериканская",
  // Казахский справочник.
  жерортатеңіздік: "Жерорта-\nтеңіздік",
};

const CYRILLIC_VOWELS = "аеёиоуыэюяіүұөәaeiouy";
/** Буквы, которым нельзя начинать строку: приклеены к предыдущей. */
const NEVER_LINE_START = "ьъй";

function isVowel(char: string): boolean {
  return CYRILLIC_VOWELS.includes(char.toLowerCase());
}

function isConsonant(char: string): boolean {
  const lower = char.toLowerCase();
  return /\p{L}/u.test(lower) && !isVowel(lower) && !NEVER_LINE_START.includes(lower);
}

/**
 * Переносит ОДНО слово по слогу: `гласная | согласная + гласная`, точка
 * разрыва — ближайшая к середине, с обеих сторон не меньше трёх букв.
 * «Средиземноморская» → «Средиземно-\nморская», «Ближневосточная» →
 * «Ближне-\nвосточная». Если подходящего места нет (слово без гласных,
 * латинская аббревиатура), слово возвращается как есть — целым, а не
 * разорванным по букве.
 */
export function hyphenateWord(word: string): string {
  const chars = Array.from(word);
  const middle = chars.length / 2;
  let best: number | undefined;
  for (let i = 3; i <= chars.length - 3; i += 1) {
    const prev = chars[i - 1];
    const next = chars[i];
    const after = chars[i + 1];
    if (prev === undefined || next === undefined || after === undefined) continue;
    if (!isVowel(prev) || !isConsonant(next) || !isVowel(after)) continue;
    if (best === undefined || Math.abs(i - middle) < Math.abs(best - middle)) best = i;
  }
  if (best === undefined) return word;
  return `${chars.slice(0, best).join("")}-\n${chars.slice(best).join("")}`;
}

/**
 * Разделитель слов. Неразрывный пробел (U+00A0) НАМЕРЕННО не разделитель:
 * он приезжает из кабинета копипастой, и RN по нему не переносит, значит для
 * раскладки это одно слово — считаем так же.
 */
const WORD_SEPARATOR = /[ \t\n\r\f\v]+/;

/**
 * Текст подписи под кругом: короткое название — как есть, одной строкой;
 * длинное слово — с явным переносом по слогу.
 */
export function cuisineLabelText(name: string): string {
  const trimmed = name.trim();
  const fromDictionary = HYPHENATION_DICTIONARY[trimmed.toLocaleLowerCase("ru-RU")];
  if (fromDictionary) return fromDictionary;
  return trimmed
    .split(WORD_SEPARATOR)
    .map((word) => (Array.from(word).length > MAX_SINGLE_LINE_CHARS ? hyphenateWord(word) : word))
    .join(" ");
}

/**
 * Сколько строк отвести подписи: одна, если текст без переносов и из одного
 * слова; две — если есть явный перенос или несколько слов (перенос по
 * пробелу). Больше двух не бывает: под подписью зарезервированы ровно две
 * строки, иначе круги соседей встали бы на разной высоте.
 */
export function cuisineLabelLines(label: string): 1 | 2 {
  return label.includes("\n") || WORD_SEPARATOR.test(label.trim()) ? 2 : 1;
}
