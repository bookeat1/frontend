import type { GuideCollection } from "@bookeat/api";

/**
 * Правила раскладки гастрогида — отдельно от вёрстки, потому что именно они
 * решают, что гость увидит, и именно их надо держать тестом.
 *
 * ГЛАВНОЕ ПРАВИЛО (лента рубрик против карточек). Лента плиток «Рубрики» и
 * большие карточки «Выбора редакции» — это ОДИН И ТОТ ЖЕ источник,
 * `GET /gastroguide/collections`; одна подборка показывается ровно один раз. Делит их редакционная привязка к рубрике:
 *
 *   - подборка помечена хотя бы одной рубрикой (`category_slugs` не пуст) —
 *     это рубричная подборка, её место в ленте («Казахская кухня», «Горы и
 *     гастрономия», «Instagram-worthy», «Кофейная культура Алматы» на проде:
 *     короткое описание в одну строку, ровно то, что рисует плитка макета);
 *   - подборка без рубрик — это лонгрид редакции, его место в списке под
 *     лентой большой карточкой: у него длинный текст и своя обложка.
 *
 * Признак взят из данных, а не выдуман: на проде 2026-08-20 ровно четыре
 * подборки помечены рубриками и ровно четыре (статьи-лонгриды) — нет.
 *
 * Вырожденные случаи не ломают экран: если рубрик нет ни у кого, лента не
 * рисуется и весь гастрогид остаётся карточками; если рубрики есть у всех —
 * остаётся одна лента. Пустое состояние показывается только когда подборок нет
 * вообще.
 */

export interface GuideSections {
  /** Подборки-рубрики — плитки горизонтальной ленты «Рубрики». */
  rubrics: GuideCollection[];
  /** Лонгриды без рубрики — большие карточки «Выбора редакции». */
  articles: GuideCollection[];
}

/**
 * Делит подборки на ленту рубрик и карточки «Выбора редакции». Порядок внутри
 * обеих групп не трогаем: его задаёт редакция на сервере.
 */
export function splitGuideCollections(collections: readonly GuideCollection[]): GuideSections {
  const rubrics: GuideCollection[] = [];
  const articles: GuideCollection[] = [];
  for (const collection of collections) {
    if (collection.categorySlugs.length > 0) rubrics.push(collection);
    else articles.push(collection);
  }
  return { rubrics, articles };
}
