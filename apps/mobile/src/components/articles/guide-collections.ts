import type { GuideCollection } from "@bookeat/api";

/**
 * Правила раскладки гастрогида — отдельно от вёрстки, потому что именно они
 * решают, что гость увидит, и именно их надо держать тестом.
 *
 * ГЛАВНОЕ ПРАВИЛО (сетка против списка). Сетка плиток и карточки под ней — это
 * ОДИН И ТОТ ЖЕ источник, `GET /gastroguide/collections`; одна подборка
 * показывается ровно один раз. Делит их редакционная привязка к рубрике:
 *
 *   - подборка помечена хотя бы одной рубрикой (`category_slugs` не пуст) —
 *     это рубричная подборка, её место в сетке («Казахская кухня», «Горы и
 *     гастрономия», «Instagram-worthy», «Кофейная культура Алматы» на проде:
 *     короткое описание в одну строку, ровно то, что рисует плитка макета);
 *   - подборка без рубрик — это лонгрид редакции, его место в списке под
 *     сеткой широкой карточкой: у него длинный текст и своя обложка.
 *
 * Признак взят из данных, а не выдуман: на проде 2026-08-20 ровно четыре
 * подборки помечены рубриками и ровно четыре (статьи-лонгриды) — нет.
 *
 * Вырожденные случаи не ломают экран: если рубрик нет ни у кого, сетка не
 * рисуется и весь гастрогид остаётся списком; если рубрики есть у всех —
 * остаётся одна сетка. Пустое состояние показывается только когда подборок нет
 * вообще.
 */

/** Колонок в сетке (макет 1099:6837 — две плитки в ряд с просветом 8). */
export const GUIDE_GRID_COLUMNS = 2;

export interface GuideSections {
  /** Подборки-рубрики — плитки сетки. */
  rubrics: GuideCollection[];
  /** Лонгриды без рубрики — широкие карточки под сеткой. */
  articles: GuideCollection[];
}

/**
 * Делит подборки на сетку и список. Порядок внутри обеих групп не трогаем: его
 * задаёт редакция на сервере.
 */
export function splitGuideCollections(collections: readonly GuideCollection[]): GuideSections {
  const rubrics: GuideCollection[] = [];
  const articles: GuideCollection[] = [];
  for (const collection of collections) {
    if (collection.categorySlugs.length > 0) rubrics.push(collection);
    else articles.push(collection);
  }
  return { rubrics, articles };
}

/**
 * Разбивка на ряды по `columns` штук. Сетка собирается рядами, а не переносом
 * строк: у RN нет процентов с вычитанием просвета, а ряд из элементов `flex: 1`
 * даёт ровно ту же геометрию, что макет. Неполный последний ряд экран
 * дополняет пустышкой, иначе одинокая плитка растянулась бы во всю ширину.
 */
export function toGridRows<T>(items: readonly T[], columns: number = GUIDE_GRID_COLUMNS): T[][] {
  if (columns < 1) return items.length > 0 ? [[...items]] : [];
  const rows: T[][] = [];
  for (let i = 0; i < items.length; i += columns) {
    rows.push(items.slice(i, i + columns));
  }
  return rows;
}
